"use client";

import { useEffect, useMemo, useState } from "react";
import {
  ArrowUpRight,
  Check,
  Clock3,
  FolderKanban,
  Plus,
  Search,
  Sparkles,
  Target,
} from "lucide-react";
import Link from "next/link";
import { AppShell, SectionTitle } from "@/components/campaign-app";
import { getAccessToken, listCampaigns, type Campaign } from "@/lib/api";

const statusLabels: Record<Campaign["status"], string> = {
  draft: "Draft",
  queued: "Queued",
  running: "In progress",
  completed: "Completed",
  failed: "Failed",
};

const statusStyles: Record<Campaign["status"], string> = {
  draft: "bg-slate-100 text-slate-600",
  queued: "bg-amber-50 text-amber-700",
  running: "bg-amber-50 text-amber-700",
  completed: "bg-emerald-50 text-emerald-700",
  failed: "bg-red-50 text-red-700",
};

export default function Dashboard() {
  const [query, setQuery] = useState("");
  const [filter, setFilter] = useState("All");
  const [campaigns, setCampaigns] = useState<Campaign[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    const token = getAccessToken();
    if (!token) return;
    listCampaigns(token)
      .then(setCampaigns)
      .catch((loadError) =>
        setError(
          loadError instanceof Error
            ? loadError.message
            : "Unable to load campaigns.",
        ),
      )
      .finally(() => setLoading(false));
  }, []);

  const items = useMemo(
    () =>
      campaigns.filter(
        (campaign) =>
          (filter === "All" || statusLabels[campaign.status] === filter) &&
          `${campaign.name} ${campaign.brief}`
            .toLowerCase()
            .includes(query.toLowerCase()),
      ),
    [campaigns, filter, query],
  );
  const completed = campaigns.filter((c) => c.status === "completed").length;
  const active = campaigns.filter((c) => ["queued", "running"].includes(c.status)).length;
  const latest = campaigns[0];

  return (
    <AppShell>
      <div className="content-wrap">
        <div className="flex flex-col justify-between gap-5 sm:flex-row sm:items-end">
          <SectionTitle
            eyebrow={new Date().toLocaleDateString(undefined, {
              weekday: "long",
              month: "long",
              day: "numeric",
            })}
            title="Your campaign workspace"
            description="Create, monitor, and review campaigns generated by your AI team."
          />
          <Link href="/campaigns/new" className="primary-button">
            <Plus size={17} /> Create campaign
          </Link>
        </div>
        <section className="stats-grid">
          <Stat icon={<FolderKanban size={17} />} label="Total campaigns" value={campaigns.length} note="Saved campaigns" />
          <Stat icon={<Check size={17} />} label="Completed" value={completed} note="Ready to review" />
          <Stat icon={<Clock3 size={17} />} label="In progress" value={active} note="Queued or running" />
          <Stat
            icon={<Sparkles size={17} />}
            label="Last campaign"
            value={latest ? new Date(latest.updated_at).toLocaleDateString(undefined, { month: "short", day: "numeric" }) : "—"}
            note={latest?.name ?? "No campaigns yet"}
          />
        </section>
        <section className="library-section">
          <div className="library-heading">
            <div>
              <h2>Your campaigns</h2>
              <p>Explore, refine, and bring your best ideas to life.</p>
            </div>
            <Link href="/campaigns/new" className="text-button">
              New brief <ArrowUpRight size={15} />
            </Link>
          </div>
          <div className="toolbar">
            <div className="search-wrap">
              <Search size={16} />
              <input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Search campaigns..." aria-label="Search campaigns" />
            </div>
            <div className="filter-pills">
              {["All", "Completed", "In progress", "Queued", "Failed", "Draft"].map((value) => (
                <button key={value} onClick={() => setFilter(value)} className={filter === value ? "filter-active" : ""}>
                  {value}
                </button>
              ))}
            </div>
          </div>
          {error && <p className="mt-5 text-sm text-red-600">{error}</p>}
          {loading && <p className="mt-8 text-sm text-slate-500">Loading your campaigns...</p>}
          {!loading && !error && items.length === 0 && (
            <div className="mt-8 rounded-2xl border border-dashed border-slate-200 p-10 text-center">
              <p className="font-semibold text-[#172033]">No campaigns found</p>
              <p className="mt-2 text-sm text-slate-500">Create your first brief to start the five-agent campaign team.</p>
            </div>
          )}
          <div className="campaign-grid">
            {items.map((campaign, index) => (
              <Link href={`/campaigns/${campaign.id}/results`} key={campaign.id} className="campaign-card">
                <div className={`campaign-art bg-gradient-to-br ${["from-violet-200 via-fuchsia-100 to-amber-100", "from-sky-100 via-cyan-50 to-emerald-100", "from-lime-100 via-emerald-50 to-yellow-100"][index % 3]}`}>
                  <div className="relative z-10 flex h-full items-center justify-center">
                    <Target size={35} strokeWidth={1.35} className="text-[#635BFF]/75" />
                  </div>
                </div>
                <div className="p-4">
                  <div className="mb-2 flex items-start justify-between gap-2">
                    <h3 className="text-[14px] font-semibold text-[#172033]">{campaign.name}</h3>
                    <span className={`rounded-full px-2.5 py-1 text-[11px] ${statusStyles[campaign.status]}`}>
                      {statusLabels[campaign.status]}
                    </span>
                  </div>
                  <p className="mb-4 line-clamp-2 min-h-[38px] text-[12px] leading-[1.55] text-slate-500">{campaign.brief}</p>
                  <div className="flex justify-between border-t border-slate-100 pt-3 text-[11px] text-slate-400">
                    <span>{new Date(campaign.updated_at).toLocaleDateString()}</span>
                    <span className="flex items-center gap-1"><Target size={12} /> Open workspace</span>
                  </div>
                </div>
              </Link>
            ))}
          </div>
        </section>
      </div>
    </AppShell>
  );
}

function Stat({ icon, label, value, note }: { icon: React.ReactNode; label: string; value: string | number; note: string }) {
  return (
    <div className="stat-card">
      <div className="stat-icon purple">{icon}</div>
      <p>{label}</p>
      <strong>{value}</strong>
      <span className="stat-note">{note}</span>
    </div>
  );
}
